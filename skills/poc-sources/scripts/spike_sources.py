#!/usr/bin/env python3
"""Manage the research sources for the spike-loop researcher agent.

Standard library only, Python 3.9+. Subcommands:

  classify          read MCP tool names (stdin or --file), print them grouped by server and
                    bucketed as read / review / write. Names are matched on their verbs, so
                    this is a safety net, not a guarantee: the user approves every tool.
  init-sources      write the sources file template if it does not exist (never overwrites).
  render-agent      write the user-scope agent `researcher-internal` from the plugin's
                    researcher agent plus the approved tools. Refuses write-class tools and
                    refuses to overwrite an agent file it did not generate.
  status            compare the approved tools in the generated agent with the tool names
                    visible now (stdin or --file): which are gone, which new read tools exist.

Exit codes: 0 ok, 1 usage or input problem, 2 refused for safety.
"""
import argparse
import datetime
import json
import os
import re
import sys

MARKER = "<!-- generated by spike-loop poc-sources: edit the sources file, then re-run the skill -->"
BASE_TOOLS = ["Read", "Bash", "WebFetch", "WebSearch", "ToolSearch"]
AGENT_NAME = "researcher-internal"

# A tool with any of these verbs can change something outside the session. Never offered.
WRITE = {
    "create", "update", "delete", "remove", "send", "post", "write", "add", "set", "move",
    "share", "unshare", "trash", "untrash", "upload", "publish", "reply", "forward", "label",
    "unlabel", "mark", "unmark", "apply", "archive", "unarchive", "restore", "duplicate",
    "copy", "rename", "cancel", "respond", "invite", "revoke", "deactivate", "activate",
    "commit", "propose", "upsert", "certify", "uncertify", "link", "unlink", "sign",
    "schedule", "approve", "reconnect", "convert", "complete", "request", "generate",
    "spawn", "start", "stop", "pin", "unpin", "clear", "clean", "discard", "merge",
    "assign", "install", "uninstall", "enable", "disable", "reset", "kill", "drop",
}
# Generic dispatchers and executors: they may do anything, so a human must look.
REVIEW_FORCE = {"run", "execute", "exec", "invoke", "call", "eval", "code", "shell", "bash", "download", "export"}
# A tool whose verb says it only reads.
READ = {
    "get", "read", "list", "search", "query", "fetch", "find", "lookup", "view", "describe",
    "introspect", "retrieve", "browse", "count", "explain", "inspect", "show", "head",
}


def split_tool(name):
    """Return (server, tool) for mcp__server__tool, else ("(unknown)", name)."""
    m = re.match(r"^mcp__(.+?)__(.+)$", name)
    if m:
        return m.group(1), m.group(2)
    return "(unknown)", name


def tokens(tool):
    return [t for t in re.split(r"[_\-]+", tool.lower()) if t]


def bucket(tool):
    """read, review or write for a bare tool name (no server part)."""
    toks = tokens(tool)
    if any(t in WRITE for t in toks):
        return "write"
    if "resolve" in toks and "library" in toks:  # resolve-library-id style lookups only read
        return "read"
    if any(t in REVIEW_FORCE for t in toks):
        return "review"
    if any(t in READ for t in toks):
        return "read"
    return "review"


def classify(names):
    out = {}
    for raw in names:
        name = raw.strip()
        if not name or name.startswith("#"):
            continue
        server, tool = split_tool(name)
        out.setdefault(server, {"read": [], "review": [], "write": []})[bucket(tool)].append(name)
    return out


def config_dir():
    base = os.environ.get("SPIKE_LOOP_CONFIG")
    if base:
        return os.path.expanduser(base)
    xdg = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return os.path.join(xdg, "spike-loop")


def sources_path():
    return os.path.join(config_dir(), "research-sources.md")


def default_agent_path():
    cfg = os.environ.get("CLAUDE_CONFIG_DIR") or os.path.expanduser("~/.claude")
    return os.path.join(cfg, "agents", AGENT_NAME + ".md")


def plugin_root():
    return os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))


SOURCES_TEMPLATE = """# Research sources

Updated: {today}
Kept by `/spike-loop:poc-sources`. You can edit this file by hand: it is plain notes the researcher reads first.
Which tools the researcher may call is not decided here. That list lives in the `researcher-internal` agent file
and is only changed by re-running the skill, so a typo in this file can never grant access.

## Notion
- (page or database, and what it holds)

## Drive
- (folder or document, and what it holds)

## Slack channels
- (channel, and what it holds)

## Email and meeting notes
- (label, folder or meeting series, and what it holds)

## Local repos and notes
- (absolute path, and what it holds)

## Priority and freshness notes
- (which source wins when two disagree, known out-of-date pages, who owns what)
"""


def cmd_classify(a):
    names = read_lines(a.file) if a.file else sys.stdin.read().splitlines()
    grouped = classify(names)
    if a.json:
        print(json.dumps(grouped, indent=2, sort_keys=True))
        return 0
    for server in sorted(grouped):
        g = grouped[server]
        print("%s  (read %d, review %d, write %d)" % (server, len(g["read"]), len(g["review"]), len(g["write"])))
        for k in ("read", "review"):
            for n in g[k]:
                print("  %-6s %s" % (k, split_tool(n)[1]))
        if g["write"]:
            print("  write  (%d excluded, never offered)" % len(g["write"]))
    return 0


def cmd_init_sources(a):
    path = a.out or sources_path()
    if os.path.exists(path):
        print("exists, left unchanged: " + path)
        return 0
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(SOURCES_TEMPLATE.format(today=datetime.date.today().isoformat()))
    os.chmod(path, 0o600)
    print("created: " + path)
    return 0


def read_lines(path):
    with open(path) as f:
        return f.read().splitlines()


def read_names(path):
    return [l.strip() for l in read_lines(path) if l.strip() and not l.startswith("#")]


def cmd_render_agent(a):
    approved = read_names(a.approved)
    bad = [n for n in approved if not re.match(r"^mcp__[^\s,]+__[^\s,]+$", n)]
    if bad:
        print("not MCP tool names: " + ", ".join(bad), file=sys.stderr)
        return 1
    writes = [n for n in approved if bucket(split_tool(n)[1]) == "write"]
    if writes:
        print("refused, write-class tools can never go into the research agent: " + ", ".join(writes), file=sys.stderr)
        return 2
    out = a.out or default_agent_path()
    if os.path.exists(out) and MARKER not in "\n".join(read_lines(out)) and not a.force:
        print("refused, %s exists and was not generated by this script (use --force to replace)" % out, file=sys.stderr)
        return 2
    base_path = a.base or os.path.join(plugin_root(), "agents", "researcher.md")
    text = "\n".join(read_lines(base_path)) + "\n"
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        print("base agent has no frontmatter: " + base_path, file=sys.stderr)
        return 1
    front, body = m.group(1), m.group(2)
    body = body.replace("You have no write tools and no connector tools.", "You have no write tools. Your connector tools are read-only.")
    tools = ", ".join(BASE_TOOLS + sorted(set(approved)))
    front = re.sub(r"^name: .*$", "name: " + AGENT_NAME, front, count=1, flags=re.M)
    front = re.sub(r"^tools: .*$", "tools: " + tools, front, count=1, flags=re.M)
    front = re.sub(
        r"^description: .*$",
        "description: Research agent with this user's approved read-only connectors (generated by /spike-loop:poc-sources). "
        "Use for questions that need internal documents, chat, email or meeting notes as well as public docs. "
        "Reads the user's research-sources file first. Cannot write to any connector.",
        front, count=1, flags=re.M)
    src = a.sources or sources_path()
    extra = (
        "\n## Internal sources\n"
        "Before searching, read `%s` if it exists. It lists where the user keeps internal documents and which source wins when two disagree. "
        "Search those places first, check last-modified dates, and prefer the newest. If the file is missing or empty, say internal sources are "
        "not configured and answer only from public sources.\n"
        "Your connector tools are read-only by construction. If a task needs a write, return it as a proposed action.\n" % src
    )
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("---\n" + front + "\n---\n" + MARKER + "\n" + body.rstrip("\n") + "\n" + extra)
    print("wrote %s with %d approved MCP tool(s)" % (out, len(approved)))
    print("Restart Claude Code before the new agent is available: agents created mid-session are not picked up.")
    return 0


def approved_in_agent(path):
    text = "\n".join(read_lines(path))
    m = re.search(r"^tools: (.*)$", text, re.M)
    if not m:
        return []
    return [t.strip() for t in m.group(1).split(",") if t.strip().startswith("mcp__")]


def cmd_status(a):
    agent = a.agent or default_agent_path()
    src = a.sources or sources_path()
    print("sources file : %s (%s)" % (src, "present" if os.path.exists(src) else "MISSING"))
    if not os.path.exists(agent):
        print("agent        : %s MISSING, run the skill setup" % agent)
        return 0
    approved = approved_in_agent(agent)
    print("agent        : %s (%d approved tool(s))" % (agent, len(approved)))
    names = read_lines(a.file) if a.file else sys.stdin.read().splitlines() if not sys.stdin.isatty() else []
    visible = {n.strip() for n in names if n.strip()}
    if not visible:
        print("no visible tool names given, skipped the comparison")
        return 0
    gone = [n for n in approved if n not in visible]
    fresh = [n for s, g in classify(visible).items() for n in g["read"] if n not in approved]
    print("approved but no longer visible (%d): %s" % (len(gone), ", ".join(split_tool(n)[1] for n in gone) or "none"))
    print("new read-class tools (%d): %s" % (len(fresh), ", ".join(split_tool(n)[1] for n in sorted(fresh)) or "none"))
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = p.add_subparsers(dest="cmd", required=True)
    c = sp.add_parser("classify"); c.add_argument("--file"); c.add_argument("--json", action="store_true"); c.set_defaults(fn=cmd_classify)
    i = sp.add_parser("init-sources"); i.add_argument("--out"); i.set_defaults(fn=cmd_init_sources)
    r = sp.add_parser("render-agent")
    r.add_argument("--approved", required=True, help="file with one approved MCP tool name per line")
    r.add_argument("--out"); r.add_argument("--base"); r.add_argument("--sources"); r.add_argument("--force", action="store_true")
    r.set_defaults(fn=cmd_render_agent)
    s = sp.add_parser("status"); s.add_argument("--file"); s.add_argument("--agent"); s.add_argument("--sources"); s.set_defaults(fn=cmd_status)
    a = p.parse_args(argv)
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
